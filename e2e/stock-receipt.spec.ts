import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";

for (const width of [390, 1440]) test(`received stock returns to its requirement for explicit count and match at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.goto("/"); await page.getByLabel("Workspace password").fill("demo-password-please-change");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Projects", exact: true })).toBeVisible();
  const id = `receipt-${randomUUID()}`, revision = `${id}-r1`;
  const csrf = (await page.context().cookies()).find(cookie => cookie.name === "forge_csrf")!.value;
  const post = async (path: string, data: object) => {
    const response = await page.request.post(`/api/v1${path}`, { headers: { "x-csrf-token": csrf, "idempotency-key": randomUUID() }, data });
    expect(response.status(), await response.text()).toBeLessThan(300); return response.json();
  };
  await post("/projects/with-initial-revision", { project: { id, name: `Synthetic receipt project ${width}`, status: "planned", description: "Receipt continuity regression." }, revision: { id: revision, name: "Initial", status: "concept", fabricationRoute: "none" } });
  await post(`/project-revisions/${revision}/bom`, { name: "Receipt connectors", requiredQuantity: 4, unit: "each", role: "consumed", optional: false, constraints: {}, alternatives: [] });
  await page.goto(`/#/projects/${id}/offers`); await page.reload();
  const row = page.locator(".sourcing-requirement");
  await expect(row.getByRole("button", { name: "Match owned stock" })).toBeVisible();
  await row.getByRole("button", { name: "Record quote for Receipt connectors" }).click();
  await row.getByLabel("Supplier", { exact: true }).fill("Synthetic supplier");
  await row.getByLabel("Supplier source URL").fill("https://supplier.example/connectors");
  await row.getByLabel("Quantity per pack", { exact: true }).fill("10");
  await row.getByLabel("Pack price", { exact: true }).fill("2.50");
  await row.getByRole("button", { name: "Save quote" }).click();
  await row.getByLabel("I checked that this quoted item meets the current requirement").check();
  await row.getByRole("button", { name: "Use reviewed quote" }).click();
  await row.getByRole("button", { name: "Record received stock" }).click();
  const add = page.getByRole("dialog", { name: "Add to inventory", exact: true });
  await expect(add.getByRole("region", { name: "Receiving for requirement" })).toContainText("Receipt connectors");
  await add.getByRole("combobox", { name: "What are you adding?" }).selectOption("electronic");
  await add.getByRole("button", { name: "Continue", exact: true }).click();
  const form = page.getByRole("dialog");
  await expect(form.getByLabel("Name", { exact: true })).toHaveValue("Receipt connectors");
  await expect(form.getByLabel("Quantity received", { exact: true })).toHaveValue("");
  await form.getByLabel("Quantity received", { exact: true }).fill("4");
  await form.getByRole("button", { name: "Add item", exact: true }).click();
  const drawer = page.getByRole("dialog", { name: /^Receipt connectors/u });
  await expect(drawer.getByRole("region", { name: "Continue receiving stock" })).toContainText("Confirm its physical count above");
  await drawer.getByLabel("Counted quantity").fill("4");
  await drawer.getByRole("button", { name: "Review physical count", exact: true }).click();
  const review = page.getByRole("alertdialog", { name: "Review physical count", exact: true });
  await review.getByRole("button", { name: "Confirm physical count", exact: true }).click();
  await expect(review).toHaveCount(0);
  await expect(drawer.getByRole("region", { name: "Continue receiving stock" })).toContainText("Physical quantity recorded");
  await drawer.getByRole("button", { name: "Review this item for the requirement" }).click();
  const edit = page.getByRole("dialog", { name: "Edit requirement", exact: true });
  await expect(edit.getByRole("button", { name: "Clear owned item selection" })).toBeVisible();
  await edit.getByRole("button", { name: "Save requirement", exact: true }).click();
  await expect(edit).toHaveCount(0);
  await page.getByRole("tab", { name: /^Requirements/u }).click();
  await expect(page.locator(".bom-row")).toContainText("Ready");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
